package payload

import (
	"fmt"
	"sort"
	"strings"
)

// agentBuildPlan is the resolved module selection for one Go agent build: the
// included catalogue entries, the excluded ones, and the derived transport
// slice flag. resolveAgentPlan is the only constructor; it also validates the
// operator's selection (unknown names, unmet dependencies).
type agentBuildPlan struct {
	Included           []string      // included module names, catalogue order
	Excluded           []AgentModule // excluded entries, catalogue order
	TransportsExcluded bool          // transports_advanced not compiled in (slim or module off)
}

// resolveAgentPlan turns an ImplantConfig into the concrete extraction plan.
// An empty Modules list means "everything"; the legacy Slim flag is the
// transports_advanced exclusion preset (see agent_modules.go).
func resolveAgentPlan(cfg *ImplantConfig) (agentBuildPlan, error) {
	if cfg == nil {
		cfg = &ImplantConfig{}
	}
	included, err := NormalizeAgentModules(cfg.Modules, cfg.Slim)
	if err != nil {
		return agentBuildPlan{}, err
	}
	// WebRTC depends on Pion, which requires Go 1.24; the Win7 build pins the
	// go1.20 toolchain, so the module is always excluded there (its task map
	// entry then reports "module not compiled in" instead of breaking the
	// build).
	if cfg.Win7Compat {
		filtered := included[:0]
		for _, name := range included {
			if name != "webrtc" {
				filtered = append(filtered, name)
			}
		}
		included = filtered
	}
	plan := agentBuildPlan{Included: included, Excluded: ExcludedAgentModules(included)}
	for _, m := range plan.Excluded {
		if m.Special == SpecialTransports {
			plan.TransportsExcluded = true
		}
	}
	return plan, nil
}

// includes reports whether the named optional module is compiled in.
func (p agentBuildPlan) includes(name string) bool {
	for _, n := range p.Included {
		if n == name {
			return true
		}
	}
	return false
}

// droppedAgentFiles is the set of embedded agent files the plan removes from
// the staged build tree: every excluded module's registry and exclusive files
// plus their _test.go counterparts (the tests reference symbols that are gone;
// staged trees are never tested, but leaving broken test files behind would be
// a trap for anyone inspecting the tree).
func (p agentBuildPlan) droppedAgentFiles() map[string]bool {
	dropped := map[string]bool{}
	add := func(name string) {
		dropped[name] = true
		if strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_test.go") {
			dropped[strings.TrimSuffix(name, ".go")+"_test.go"] = true
		}
	}
	for _, m := range p.Excluded {
		for _, f := range m.RegistryFiles {
			add(f)
		}
		for _, f := range m.ExclusiveFiles {
			add(f)
		}
	}
	return dropped
}

// moduleExcludedSource renders the generator-injected modules_excluded.go — the
// data half of the agent-side module bookkeeping (task_modules.go holds the
// helpers; modules_default.go is the hand-build fallback and is dropped from
// every staged tree). The content is deliberately deterministic (catalogue
// order, sorted task map) so staged trees are diffable.
func (p agentBuildPlan) moduleExcludedSource() string {
	var b strings.Builder
	b.WriteString("package main\n\n")
	b.WriteString("// Code generated by the ForgeC2 generator (agent module selection). DO NOT EDIT.\n//\n")
	b.WriteString("// The operator excluded the modules below at generation time: their registry\n")
	b.WriteString("// files were dropped from this build, so help marks the affected commands and\n")
	b.WriteString("// executeTask answers their task types with the owning module instead of the\n")
	b.WriteString("// generic \"unknown task type\" error.\n\n")
	if len(p.Included) == 0 {
		// Empty but non-nil: the agent-side summary must read this as "core
		// only", not as the nil hand-build fallback.
		b.WriteString("// Core only: every optional module was excluded.\nvar compiledAgentModules = []string{}\n\n")
	} else {
		b.WriteString("var compiledAgentModules = []string{\n")
		for _, name := range p.Included {
			fmt.Fprintf(&b, "\t%q,\n", name)
		}
		b.WriteString("}\n\n")
	}
	tasks := AgentModuleExcludedTasks(p.Excluded)
	if len(tasks) == 0 {
		b.WriteString("var excludedModuleTasks = map[string]string{}\n")
		return b.String()
	}
	keys := make([]string, 0, len(tasks))
	for k := range tasks {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("var excludedModuleTasks = map[string]string{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: %q,\n", k, tasks[k])
	}
	b.WriteString("}\n")
	return b.String()
}
