#!/usr/bin/env node
// gen-permissions.mjs — generate src/lib/permission-keys.ts from the backend
// permission constants in internal/db/models.go (the single source of truth).
// The frontend can (and must) compile against this type, so typos like
// "agents.readd" fail at build time instead of silently gating UI.
//
// Usage: node scripts/gen-permissions.mjs   (from frontend/)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, normalize } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const modelsPath = join(here, "..", "..", "internal", "db", "models.go");
const outPath = join(here, "..", "src", "lib", "permission-keys.ts");

export function filePath() {
  return outPath;
}

export function generate() {
  const src = readFileSync(modelsPath, "utf8");
  const keys = [...src.matchAll(/^[ \t]*Perm\w+\s*=\s*"([^"]+)"[ \t]*$/gm)]
    .map((m) => m[1])
    .sort();
  if (keys.length === 0) {
    throw new Error(`no Perm* constants found in ${modelsPath}`);
  }
  const union = keys.map((k) => `  | "${k}"`).join("\n");
  return `/**
 * GENERATED by scripts/gen-permissions.mjs — DO NOT EDIT BY HAND.
 * Permission wire values mirroring internal/db/models.go (Perm* constants).
 * Regenerate with:  npm run gen:permissions
 */
export type PermissionKey =
${union};
`;
}

const isMain =
  !!process.argv[1] &&
  normalize(fileURLToPath(import.meta.url)) === normalize(process.argv[1]);

if (isMain) {
  writeFileSync(outPath, generate(), "utf8");
  console.log(`Wrote ${outPath}`);
}